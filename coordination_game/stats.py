"""Statistical analysis (plan in results/REPORT_EXPERIMENTS.md; decisions signed off 2026-11-08).

    python -m coordination_game.stats        # -> results/stats.md

Session = unit. Non-converged games count as 15 rounds. Nonparametric tests, exact where available; Holm within each family;
two-sided alpha 0.05; 95% percentile bootstrap CIs (10,000 resamples, seed 0). Decisions: learning = per-session Spearman
slope (primary) + game 1 vs 10 (secondary); vote chance = 1/10; ties at the top reported separately; shuffled vote primary.
"""
from __future__ import annotations

import glob
import json
from collections import Counter
from pathlib import Path

import numpy as np
from scipy import stats as ss

from .report_figures import (MODELS, LABEL, holder_item, jl, r2_share, rounds_by_game, sessions, votes)

RNG = np.random.default_rng(0)
OUT = Path("results/stats.md")
L: list[str] = []
TABLES: list[dict] = []  # every table, also written as LaTeX (booktabs) to paper/appendix/tables/
_heading = [""]


def p(*a):
    line = " ".join(str(x) for x in a)
    if line.startswith("## "):
        _heading[0] = line[3:]
    L.append(line)


def boot(x, f=np.mean, n=10000):
    x = np.asarray(x, float)
    x = x[~np.isnan(x)]
    if len(x) < 2:
        return (f(x) if len(x) else np.nan), np.nan, np.nan
    bs = f(RNG.choice(x, (n, len(x))), axis=1)
    return f(x), np.percentile(bs, 2.5), np.percentile(bs, 97.5)


def boot_diff(a, b, n=10000):
    a, b = np.asarray(a, float), np.asarray(b, float)
    d = RNG.choice(a, (n, len(a))).mean(1) - RNG.choice(b, (n, len(b))).mean(1)
    return a.mean() - b.mean(), np.percentile(d, 2.5), np.percentile(d, 97.5)


def holm(pvals):
    pv = np.asarray(pvals, float)
    order = np.argsort(pv)
    adj = np.empty_like(pv)
    run = 0.0
    for rank, i in enumerate(order):
        run = max(run, (len(pv) - rank) * pv[i])
        adj[i] = min(1.0, run)
    return adj


def fmt_p(x):
    return "<0.001" if x < 0.001 else f"{x:.3f}"


def rb_mwu(a, b):  # rank-biserial correlation for Mann-Whitney
    u = ss.mannwhitneyu(a, b, alternative="two-sided").statistic
    return 2 * u / (len(a) * len(b)) - 1


def wilcoxon(x, y=None):
    d = np.asarray(x, float) - (0 if y is None else np.asarray(y, float))
    d = d[d != 0]
    if len(d) == 0:
        return np.nan, 1.0, 0
    r = ss.wilcoxon(d, alternative="two-sided", method="exact" if len(d) <= 25 else "auto")
    return r.statistic, r.pvalue, len(d)


def table(header, rows, caption=None):
    TABLES.append({"caption": caption or _heading[0], "header": list(header), "rows": [list(map(str, r)) for r in rows]})
    p("| " + " | ".join(header) + " |")
    p("|" + "---|" * len(header))
    for r in rows:
        p("| " + " | ".join(str(x) for x in r) + " |")
    p("")


def S(arm, m):
    return sessions(f"runs/overnight1/{arm}/{m}/s*")


def yielding(d):
    return r2_share(d, holder_item, lambda g: g["bad_apple_picks"].keys())


def holder_id(d):
    return json.load(open(d / "config.json"))["config"]["bad_apple_ids"][0]


def main():
    p("# Statistical results")
    p("")
    p("Generated by `python -m coordination_game.stats`. Session = unit; tests two-sided; Holm-adjusted p within each family "
      "(column p_Holm); 95% bootstrap CIs over sessions (10,000 resamples, seed 0). Non-converged games = 15 rounds.")
    p("")

    # ---------- H1 ----------
    p("## H1. A bad apple slows convergence (per model)")
    p("Outcome: session mean rounds over 10 games. Mann–Whitney U, bad apple vs control. Effect: difference in means [95% CI], rank-biserial r.")
    p("")
    rows, pv = [], []
    for m in MODELS:
        a = [np.mean(rounds_by_game(d)) for d in S("badapple", m)]
        b = [np.mean(rounds_by_game(d)) for d in S("control", m)]
        res = ss.mannwhitneyu(a, b, alternative="two-sided", method="exact")
        dif = boot_diff(a, b)
        conv = sum(g["converged"] for d in S("badapple", m) for g in jl(d / "games.jsonl"))
        rows.append([LABEL[m], f"{len(a)} / {len(b)}", f"{np.mean(a):.2f}", f"{np.mean(b):.2f}",
                     f"{dif[0]:+.2f} [{dif[1]:+.2f}, {dif[2]:+.2f}]", f"{rb_mwu(a, b):.2f}", f"{conv}/{10 * len(a)}",
                     fmt_p(res.pvalue)])
        pv.append(res.pvalue)
    for r, q in zip(rows, holm(pv)):
        r.append(fmt_p(q))
    table(["model", "n bad/ctrl", "bad apple", "control", "difference [95% CI]", "r", "bad-apple games converged", "p", "p_Holm"], rows)

    # ---------- H2 ----------
    p("## H2. Groups learn within a session (bad-apple arm)")
    p("Primary: per-session Spearman ρ between game index and rounds; Wilcoxon signed-rank of the session ρ's against 0. "
      "Secondary: game 1 vs game 10 rounds, Wilcoxon signed-rank (paired within session). Models that sit at the cap in every "
      "game have no variation (ρ undefined) and are marked n/a.")
    p("")
    rows, pv1, pv2 = [], [], []
    for m in MODELS:
        rs = [rounds_by_game(d) for d in S("badapple", m)]
        rhos = [ss.spearmanr(range(1, 11), r).statistic for r in rs if len(set(r)) > 1]
        g1, g10 = [r[0] for r in rs], [r[9] for r in rs]
        _, pA, nA = wilcoxon(rhos) if len(rhos) >= 2 else (np.nan, np.nan, 0)
        _, pB, nB = wilcoxon(g1, g10)
        mr = boot(rhos)
        rows.append([LABEL[m], len(rs), f"{len(rhos)}", f"{mr[0]:.2f} [{mr[1]:.2f}, {mr[2]:.2f}]" if rhos else "n/a",
                     fmt_p(pA) if pA == pA else "n/a", f"{np.mean(g1):.1f} → {np.mean(g10):.1f}", fmt_p(pB)])
        pv1.append(pA if pA == pA else 1.0); pv2.append(pB)
    for r, q1, q2 in zip(rows, holm(pv1), holm(pv2)):
        r.insert(5, fmt_p(q1)); r.append(fmt_p(q2))
    table(["model", "n", "sessions with variation", "mean ρ(game, rounds) [95% CI]", "p (ρ≠0)", "p_Holm", "game 1 → 10 rounds",
           "p (1 vs 10)", "p_Holm"], rows)

    # ---------- H3 ----------
    p("## H3. Models differ in how much they yield")
    p("Outcome: session mean share of LLM agents on the bad apple's item in round 2, games 6–10. Kruskal–Wallis across 7 models, "
      "then pairwise Mann–Whitney with Holm over 21 pairs.")
    p("")
    Y = {m: [np.nanmean(yielding(d)[5:]) for d in S("badapple", m)] for m in MODELS}
    kw = ss.kruskal(*[Y[m] for m in MODELS])
    p(f"Kruskal–Wallis H = {kw.statistic:.1f}, df = {len(MODELS) - 1}, p = {fmt_p(kw.pvalue)}.")
    p("")
    table(["model", "n", "yielding games 6–10 [95% CI]"],
          [[LABEL[m], len(Y[m]), "{:.2f} [{:.2f}, {:.2f}]".format(*boot(Y[m]))] for m in MODELS])
    pairs, pv = [], []
    for i, a in enumerate(MODELS):
        for b in MODELS[i + 1:]:
            if np.ptp(Y[a] + Y[b]) == 0:
                pairs.append((a, b, 1.0)); pv.append(1.0); continue
            r = ss.mannwhitneyu(Y[a], Y[b], alternative="two-sided")
            pairs.append((a, b, r.pvalue)); pv.append(r.pvalue)
    adj = holm(pv)
    sig = [f"{LABEL[a]} vs {LABEL[b]} (p_Holm {fmt_p(q)})" for (a, b, _), q in zip(pairs, adj) if q < 0.05]
    p(f"Pairs significant after Holm ({len(sig)}/21): " + "; ".join(sig) + ".")
    p("")

    # ---------- H4 ----------
    p("## H4. Leader vote: yielders elect the bad apple; non-yielders don't")
    p("Outcome: share of votes for the bad apple (shuffled list = primary; sorted = robustness). Per model: one-sample Wilcoxon "
      "of session shares vs chance 1/10 (Holm over models). Holder 'win' = strictly most votes; ties at the top reported separately.")
    p("")
    for sub, name in (("post_discussion_shuffled", "shuffled (primary)"), ("post_discussion", "sorted (robustness)")):
        rows, pv = [], []
        for m in MODELS:
            sh, win, tie = [], 0, 0
            for d in S("badapple", m):
                v = votes(d, sub)
                if not v:
                    continue
                h = holder_id(d)
                t = Counter(x for x in v.values() if x is not None)
                sh.append(t.get(h, 0) / len(v))
                top = max(t.values())
                leaders = [k for k, n in t.items() if n == top]
                win += leaders == [h]; tie += (h in leaders and len(leaders) > 1)
            _, pw, _ = wilcoxon(np.array(sh) - 0.1)
            rows.append([LABEL[m], len(sh), "{:.2f} [{:.2f}, {:.2f}]".format(*boot(sh)), f"{win}/{len(sh)}", tie, fmt_p(pw)])
            pv.append(pw)
        for r, q in zip(rows, holm(pv)):
            r.append(fmt_p(q))
        p(f"**{name}**")
        p("")
        table(["model", "n", "holder vote share [95% CI]", "holder won outright", "ties incl. holder", "p vs 1/10", "p_Holm"], rows)
    xs, ys = [], []
    for m in MODELS:
        for d in S("badapple", m):
            v = votes(d, "post_discussion_shuffled")
            if v:
                xs.append(np.nanmean(yielding(d)[5:])); ys.append(sum(x == holder_id(d) for x in v.values()) / len(v))
    rho = ss.spearmanr(xs, ys)
    p(f"Across sessions (n = {len(xs)}), Spearman ρ(yielding in games 6–10, holder vote share) = {rho.statistic:.2f}, p = {fmt_p(rho.pvalue)}.")
    within = [(m, ss.spearmanr([np.nanmean(yielding(d)[5:]) for d in S('badapple', m)],
                                [sum(x == holder_id(d) for x in votes(d, 'post_discussion_shuffled').values()) / len(votes(d, 'post_discussion_shuffled'))
                                 for d in S('badapple', m)])) for m in ["qwen3.8-27b"]]
    for m, r in within:
        p(f"Within {LABEL[m]} (the only model with spread on both): ρ = {r.statistic:.2f}, p = {fmt_p(r.pvalue)}, n = {len(S('badapple', m))}.")
    p("")

    # ---------- H5 ----------
    p("## H5. Control arm: the Agent 1 default is mostly list position")
    p("Same 35 control sessions voted twice. Outcome: Agent 1 wins outright. Exact McNemar (binomial on discordant pairs) for "
      "sorted vs shuffled; exact binomial of each vs chance 1/10.")
    p("")
    a1 = {}
    for sub in ("post_discussion", "post_discussion_shuffled"):
        for m in MODELS:
            for d in S("control", m):
                v = votes(d, sub)
                t = Counter(x for x in v.values() if x is not None)
                top = max(t.values())
                a1[(sub, str(d))] = [k for k, n in t.items() if n == top] == [1]
    keys = sorted({k for _, k in a1})
    s_ = [a1[("post_discussion", k)] for k in keys]; h_ = [a1[("post_discussion_shuffled", k)] for k in keys]
    b01 = sum(x and not y for x, y in zip(s_, h_)); b10 = sum(y and not x for x, y in zip(s_, h_))
    mc = ss.binomtest(b01, b01 + b10, 0.5).pvalue if b01 + b10 else 1.0
    p(f"Agent 1 won: sorted {sum(s_)}/{len(keys)}, shuffled {sum(h_)}/{len(keys)}; discordant pairs {b01} (sorted only) vs {b10} "
      f"(shuffled only); McNemar exact p = {fmt_p(mc)}.")
    for name, x in (("sorted", s_), ("shuffled", h_)):
        p(f"- {name} vs chance 1/10: binomial p = {fmt_p(ss.binomtest(sum(x), len(x), 0.1).pvalue)}")
    p("")
    table(["display order", "Agent 1 won outright", "p vs chance 1/10 (binomial)"],
          [["sorted (A1 first)", f"{sum(s_)}/{len(keys)}", fmt_p(ss.binomtest(sum(s_), len(s_), 0.1).pvalue)],
           ["shuffled per viewer", f"{sum(h_)}/{len(keys)}", fmt_p(ss.binomtest(sum(h_), len(h_), 0.1).pvalue)],
           ["sorted vs shuffled (exact McNemar)", f"discordant {b01} vs {b10}", fmt_p(mc)]])

    # ---------- H6 ----------
    p("## H6. Chat + a talking confederate (Gemma)")
    p("Outcome: games converged out of 10 per session. Mann–Whitney chat (n=5) vs no-chat bad apple (n=10); Fisher's exact on sessions "
      "with ≥1 converged game. Holm over the 2 models.")
    p("")
    rows, pv = [], []
    for m in ["gemma-4-31b-it", "gemma-4-26b-a4b-it"]:
        c = [sum(g["converged"] for g in jl(d / "games.jsonl")) for d in sessions(f"runs/chat_trap/chat_confed_safe/{m}/s*")]
        n = [sum(g["converged"] for g in jl(d / "games.jsonl")) for d in S("badapple", m)]
        mw = ss.mannwhitneyu(c, n, alternative="two-sided", method="exact")
        fe = ss.fisher_exact([[sum(x > 0 for x in c), sum(x == 0 for x in c)], [sum(x > 0 for x in n), sum(x == 0 for x in n)]])
        rows.append([LABEL[m], f"{sum(c)}/{10 * len(c)}", f"{sum(n)}/{10 * len(n)}", f"{rb_mwu(c, n):.2f}", fmt_p(mw.pvalue), fmt_p(fe.pvalue)])
        pv.append(mw.pvalue)
    for r, q in zip(rows, holm(pv)):
        r.insert(5, fmt_p(q))
    table(["model", "converged, chat", "converged, no chat", "r", "p (MWU)", "p_Holm", "p (Fisher, sessions)"], rows)
    p("Caveat: chat and a holdout that can announce it won't move are confounded; no silent-holder arm was run.")
    p("")

    # ---------- H7-H9 ----------
    p("## H7–H9. Holder swap and relabel (GLM-5.2, n=10 each, paired by seed)")
    p("")
    swap = sessions("runs/swap1/badapple_swap/glm-5.2/s*")
    rel = sessions("runs/relabel1/badapple_relabel/glm-5.2/s*")

    def r2_swap(d):
        return r2_share(d, lambda g: g["bad_apple_picks"][str(g.get("holder_ids", [int(next(iter(g["bad_apple_picks"])))])[0])],
                        lambda g: g.get("holder_ids", list(g["bad_apple_picks"])))

    def r2_rel(d):
        c = json.load(open(d / "config.json"))["config"]
        return r2_share(d, holder_item, lambda g: [c["bad_apple_ids"][0], c["relabel_partner"]])

    rows, pv = [], []
    for name, sess, f in (("swap", swap, r2_swap), ("relabel", rel, r2_rel)):
        R = np.array([rounds_by_game(d) for d in sess], float)
        Y_ = np.array([f(d) for d in sess], float)
        _, p57, _ = wilcoxon(R[:, 5], R[:, 4])
        _, p610, _ = wilcoxon(Y_[:, 9], Y_[:, 5])
        rows.append([name, len(sess), f"{R[:, 4].mean():.1f} → {R[:, 5].mean():.1f}", fmt_p(p57),
                     f"{np.nanmean(Y_[:, 4]):.2f}", f"{np.nanmean(Y_[:, 5]):.2f}", f"{np.nanmean(Y_[:, 9]):.2f}", fmt_p(p610)])
        pv += [p57, p610]
    adj = holm(pv)
    for i, r in enumerate(rows):
        r.insert(4, fmt_p(adj[2 * i])); r.append(fmt_p(adj[2 * i + 1]))
    table(["condition", "n", "rounds game 5 → 6", "p (5 vs 6)", "p_Holm", "R2 share on holder, game 5", "game 6", "game 10",
           "p (game 6 vs 10)", "p_Holm"], rows)
    old_copy = {}
    for name, sess in (("swap", swap), ("relabel", rel)):
        k = n = 0
        for d in sess:
            c = json.load(open(d / "config.json"))["config"]
            old = c["bad_apple_ids"][0]
            other = c.get("relabel_partner") or c["swap_bad_apple_ids"][0]
            P = {(r["game"], r["round"]): r["picks"] for r in jl(d / "rounds.jsonl")}
            src = P[(6, 1)][str(other if name == "relabel" else old)]  # relabel: the agent viewers see under the old label
            for a, v in P[(6, 2)].items():
                if int(a) not in (old, other):
                    n += 1; k += v == src
        old_copy[name] = (k, n)
    p(f"H7 (descriptive): in game 6 round 2, agents copying the old identity's round-1 pick: swap {old_copy['swap'][0]}/{old_copy['swap'][1]}, "
      f"relabel {old_copy['relabel'][0]}/{old_copy['relabel'][1]}; on the new holder's item: 0 in both.")
    seeds = sorted({d.name for d in swap} & {d.name for d in rel})
    a = [rounds_by_game(Path(f"runs/swap1/badapple_swap/glm-5.2/{s}"))[5] for s in seeds]
    b = [rounds_by_game(Path(f"runs/relabel1/badapple_relabel/glm-5.2/{s}"))[5] for s in seeds]
    _, p8, _ = wilcoxon(a, b)
    p(f"H8: game-6 rounds, swap {np.mean(a):.1f} vs relabel {np.mean(b):.1f} (paired by seed, n = {len(seeds)}), Wilcoxon p = {fmt_p(p8)}.")
    p("")

    # ---------- H10 ----------
    p("## H10. Copies coordinate above chance (one-shot Schelling)")
    p("Outcome: per-board probability that two samples of the model match (12 boards). One-sample Wilcoxon over boards vs 0.05; "
      "bootstrap CI over boards; Holm over 6 models.")
    p("")
    rows, pv = [], []
    for m in [x for x in MODELS if x != "qwen3.8-27b"]:
        by = {}
        for r in jl(Path("runs/schelling1") / m / "calls.jsonl"):
            by.setdefault(r["board_seed"], []).append(r["pick"])
        w = []
        for b_, ps in sorted(by.items()):
            c = Counter(x for x in ps if x is not None); n = len(ps)
            w.append(sum(k * (k - 1) for k in c.values()) / (n * (n - 1)))
        _, pw, _ = wilcoxon(np.array(w) - 0.05)
        rows.append([LABEL[m], len(w), "{:.2f} [{:.2f}, {:.2f}]".format(*boot(w)), f"{np.mean(w) / 0.05:.1f}×", fmt_p(pw)])
        pv.append(pw)
    for r, q in zip(rows, holm(pv)):
        r.append(fmt_p(q))
    table(["model", "boards", "copy-match [95% CI]", "× chance", "p vs 0.05", "p_Holm"], rows)

    # ---------- board-order replication ----------
    bs = {m: sessions(f"runs/boardshuf1/badapple_boardshuf/{m}/s*") for m in ["deepseek-v4-flash", "glm-53-flash"]}
    if any(bs.values()):
        p("## Robustness: board order (boards 0–9 in a per-seed random order)")
        p("If learning were 'later boards are easier', rounds would track the board, not the game index. Per session: Spearman ρ "
          "of rounds on game index; compared with the same seeds' fixed-order overnight1 sessions (Mann–Whitney).")
        p("")
        rows = []
        for m, sess in bs.items():
            if not sess:
                continue
            rh = [ss.spearmanr(range(1, 11), rounds_by_game(d)).statistic for d in sess if len(set(rounds_by_game(d))) > 1]
            base = [ss.spearmanr(range(1, 11), rounds_by_game(d)).statistic for d in S("badapple", m) if len(set(rounds_by_game(d))) > 1]
            _, pw, _ = wilcoxon(rh)
            mw = ss.mannwhitneyu(rh, base, alternative="two-sided")
            g1 = np.mean([rounds_by_game(d)[0] for d in sess]); g10 = np.mean([rounds_by_game(d)[9] for d in sess])
            rows.append([LABEL[m], len(sess), "{:.2f} [{:.2f}, {:.2f}]".format(*boot(rh)), fmt_p(pw),
                         f"{g1:.1f} → {g10:.1f}", "{:.2f}".format(np.mean(base)), fmt_p(mw.pvalue)])
        table(["model", "n (shuffled order)", "mean ρ(game, rounds) [95% CI]", "p (ρ≠0)", "game 1 → 10 rounds",
               "fixed-order mean ρ", "p (shuffled vs fixed)"], rows)

    extra_sections()
    OUT.write_text("\n".join(L) + "\n")
    print("\n".join(L))
    write_latex()



def schelling_by_board(root, model, boards=None):
    by = {}
    for r in jl(Path(root) / model / "calls.jsonl"):
        if boards is None or r["board_seed"] in boards:
            by.setdefault(r["board_seed"], []).append(r["pick"])
    out = []
    for b_, ps in sorted(by.items()):
        c = Counter(x for x in ps if x is not None); n = len(ps)
        if n > 1:
            out.append(sum(k * (k - 1) for k in c.values()) / (n * (n - 1)))
    return out


def extra_sections():
    # ---------- Schelling tell / no-tell ----------
    p("## Schelling framing: told nothing / told 'copies of you' / told 'different models' (boards 0-3)")
    p("Copy-match per board, mean over the 4 boards. Within model, Wilcoxon signed-rank paired by board vs the no-framing baseline "
      "(n = 4 boards: the smallest possible exact p is 0.125, so these are descriptive).")
    p("")
    rows = []
    for m in [x for x in MODELS if x != "qwen3.5-397b"]:
        b0 = schelling_by_board("runs/schelling1", m, {0, 1, 2, 3})
        bc = schelling_by_board("runs/schelling_copies", m, {0, 1, 2, 3})
        bo = schelling_by_board("runs/schelling_others", m, {0, 1, 2, 3})
        if not (b0 and bc and bo):
            continue
        rows.append([LABEL[m], f"{np.mean(b0):.2f}", f"{np.mean(bc):.2f}", f"{np.mean(bo):.2f}",
                     f"{np.mean(bc) - np.mean(b0):+.2f}", f"{np.mean(bo) - np.mean(b0):+.2f}"])
    table(["model", "no framing", "'copies of you'", "'different models'", "copies − none", "different − none"], rows)

    # ---------- mixed-model groups ----------
    mc = sessions("runs/mixed1_control/control/mix-six/s*")
    if mc:
        p("## Mixed-model groups (9-10 agents drawn from 6 models; no Qwen3.5-397B)")
        p("Session mean rounds to consensus; Mann–Whitney vs all same-model control sessions pooled.")
        p("")
        mix = [np.mean(rounds_by_game(d)) for d in mc]
        same = [np.mean(rounds_by_game(d)) for m in MODELS for d in S("control", m)]
        mw = ss.mannwhitneyu(mix, same, alternative="two-sided")
        rows = [["control, mixed models", len(mix), "{:.2f} [{:.2f}, {:.2f}]".format(*boot(mix)),
                 f"{sum(g['converged'] for d in mc for g in jl(d / 'games.jsonl'))}/{10 * len(mc)}", fmt_p(mw.pvalue)],
                ["control, same model (all 7)", len(same), "{:.2f} [{:.2f}, {:.2f}]".format(*boot(same)), "350/350", "–"]]
        mb = sessions("runs/mixed1_badapple/badapple/mix-six/s*")
        if mb:
            mbr = [np.mean(rounds_by_game(d)) for d in mb]
            rows.append(["bad apple, mixed models", len(mb), "{:.2f} [{:.2f}, {:.2f}]".format(*boot(mbr)),
                         f"{sum(g['converged'] for d in mb for g in jl(d / 'games.jsonl'))}/{10 * len(mb)}", "–"])
